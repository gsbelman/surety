// Copies the SuretyEscrow ABI from the Foundry artifact into the app and the agent.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = new URL("../contracts/out/SuretyEscrow.sol/SuretyEscrow.json", import.meta.url);
const target = new URL("../app/src/contract/abi.ts", import.meta.url);
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));

const erc20 = [
  "function allowance(address owner, address spender) view returns (uint256)",
  "function approve(address spender, uint256 amount) returns (bool)",
  "function balanceOf(address account) view returns (uint256)",
  "function transfer(address to, uint256 amount) returns (bool)",
];

writeFileSync(
  target,
  `// Generated by scripts/sync-abi.mjs. Do not edit.
import { parseAbi } from "viem";

export const suretyAbi = ${JSON.stringify(abi, null, 2)} as const;

export const erc20Abi = parseAbi(${JSON.stringify(erc20, null, 2)} as const);
`,
);
console.log(`Wrote ${abi.length} ABI items.`);
